"""Heavy layer: fit PCA style vectors, materialize them, and write the sanity report.

    python scripts/style_fit.py fit                     # all scheduled refits + vectors -> models.db
    python scripts/style_fit.py fit --refit-months 1    # monthly refits (another config hash)
    python scripts/style_fit.py report                  # docs/style_report.md for the latest fits
    python scripts/style_fit.py show "Roger Federer" --as-of 2019-07-01

`fit` replaces every stored fit (and its vectors) of the same configuration. Vectors are
materialized for each (player, edition start) where a charted player played a backbone
match; get_style() computes any other date on demand. Per-match counts (~90 s to parse)
are cached under models/style/ per tennis.db build.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import date, timedelta
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from tennis import heavy, models_db                     # noqa: E402
from tennis.style_features import FEATURES, SIDES       # noqa: E402

REPORT = ROOT / "docs" / "style_report.md"
WELL_KNOWN = {
    "atp": ["Roger Federer", "Rafael Nadal", "Novak Djokovic", "John Isner", "Daniil Medvedev",
            "Carlos Alcaraz", "Diego Schwartzman", "Nick Kyrgios"],
    "wta": ["Iga Swiatek", "Serena Williams", "Aryna Sabalenka", "Ashleigh Barty", "Simona Halep",
            "Coco Gauff"],
}


def config_from(args) -> heavy.HeavyConfig:
    return heavy.HeavyConfig(variance=args.variance, max_components=args.max_components,
                             refit_months=args.refit_months, min_fit_matches=args.min_fit_matches,
                             min_fit_players=args.min_fit_players)


def open_dbs(args):
    con = models_db.connect(args.models)
    models_db.attach_data(con, args.data)
    row = con.execute("SELECT value FROM data.schema_meta WHERE key='built_at'").fetchone()
    return con, (row[0] if row else None)


def cmd_fit(args) -> int:
    cfg = config_from(args)
    con, built = open_dbs(args)
    t = time.perf_counter()
    mc = heavy.load_counts(con, built_at=built)
    print(f"counts: {len(mc):,} player-match rows, {len(set(mc.match_id)):,} charted matches "
          f"({time.perf_counter() - t:.0f}s); skipped points: {sum(mc.skipped.values()):,}")
    for reason, n in mc.skipped.most_common():
        print(f"  {n:>7,}  {reason}")
    model = heavy.StyleModel(mc, cfg)
    fits = model.fit_all(first=args.first)
    print(f"{len(fits)} fits (config {cfg.config_hash})")
    con.execute("DELETE FROM style_fit WHERE config_hash=?", (cfg.config_hash,))
    for f in fits:
        heavy.save_fit(con, f, cfg, data_built_at=built)
    con.commit()
    if args.no_vectors:
        return 0
    t = time.perf_counter()
    pairs = heavy.backbone_pairs(con, set(model.tour_of))
    n = heavy.materialize(con, model, pairs, models_db.player_keys(con))
    print(f"style_vectors: {n:,} rows from {len(pairs):,} (player, edition) pairs "
          f"({time.perf_counter() - t:.0f}s)")
    return 0


def _names(con) -> dict[int, str]:
    return dict(con.execute("SELECT player_id, canonical_name FROM data.player"))


def _vectors_at(model: heavy.StyleModel, tour: str, side: str, as_of: str, min_matches: int):
    ids, vecs, nm = [], [], []
    for p, t in model.tour_of.items():
        if t != tour:
            continue
        sv = model.style(p, as_of, side)
        if sv is not None and sv.n_matches >= min_matches:
            ids.append(p); vecs.append(sv.vector); nm.append(sv.n_matches)
    return ids, np.array(vecs), nm


def cmd_report(args) -> int:
    cfg = config_from(args)
    con, built = open_dbs(args)
    mc = heavy.load_counts(con, built_at=built)
    model = heavy.StyleModel(mc, cfg, heavy.load_fits(con, cfg))
    if not model.fits:
        raise SystemExit(f"no fits stored for config {cfg.config_hash}; run `fit` first")
    names = _names(con)
    by_name = {}
    for pid, nm in names.items():
        by_name.setdefault(nm, []).append(pid)
    last_data = max(str(d) for d in mc.date)
    as_of = args.as_of or (date.fromisoformat(last_data) + timedelta(days=1)).isoformat()

    out = ["# Style vectors: sanity report", "",
           f"Generated by `scripts/style_fit.py report` (config `{cfg.config_hash}`: "
           f"{json.dumps(cfg.as_dict(), sort_keys=True)}). tennis.db built {built}. "
           f"Vectors as of {as_of} (charted matches from editions starting before it).",
           "", "For human review; not an automated gate. Loadings are in standardized-feature "
           "units after the sign convention (each component's largest-magnitude loading is positive).",
           "", f"Skipped points while parsing: {sum(mc.skipped.values()):,} of "
           f"{sum(mc.skipped.values()) + int(sum(mc.points['serve'])):,}: "
           + ", ".join(f"{r} {n:,}" for r, n in mc.skipped.most_common()) + "."]
    for tour in heavy.TOURS:
        for side in SIDES:
            fit = model.fit_for(tour, side, as_of)
            if fit is None:
                continue
            out += ["", f"## {tour.upper()} {side}", "",
                    f"Fit `{fit.fit_id}`: {fit.n_players} players with >= {cfg.min_fit_matches} charted "
                    f"matches, data {fit.data_from} .. {fit.data_to}. "
                    f"{fit.n_components} components, cumulative explained variance "
                    f"{fit.explained.sum():.1%}.", "",
                    "| component | explained | top loadings |", "|---|---|---|"]
            L = fit.loadings()
            for c in range(fit.n_components):
                order = np.argsort(-np.abs(L[:, c]))[:5]
                tops = ", ".join(f"{fit.features[i]} {L[i, c]:+.2f}" for i in order)
                out.append(f"| c{c + 1} | {fit.explained[c]:.1%} | {tops} |")
            out += ["", "Feature means and prior strength k (shrinkage pseudo-count):", "",
                    "| feature | tour mean | k |", "|---|---|---|"]
            out += [f"| {f} | {fit.tour_mean[i]:.3f} | {fit.prior_k[i]:.0f} |"
                    for i, f in enumerate(fit.features)]
            ids, V, nmatch = _vectors_at(model, tour, side, as_of, args.min_neighbour_matches)
            if len(ids) < 2:
                continue
            out += ["", f"Nearest neighbours (Euclidean in component space, among {len(ids)} players "
                    f"with >= {args.min_neighbour_matches} charted matches):", "",
                    "| player | matches | c1..c3 | nearest |", "|---|---|---|---|"]
            index = {p: i for i, p in enumerate(ids)}
            for nm in WELL_KNOWN[tour]:
                pid = next((p for p in by_name.get(nm, []) if p in index), None)
                if pid is None:
                    sv = next((model.style(p, as_of, side) for p in by_name.get(nm, [])
                               if model.tour_of.get(p) == tour), None)
                    why = (f"{sv.n_matches} charted matches, below the cutoff" if sv
                           else "no charted matches")
                    out.append(f"| {nm} | {sv.n_matches if sv else 0} | ({why}) | |"); continue
                i = index[pid]
                d = np.linalg.norm(V - V[i], axis=1)
                near = [j for j in np.argsort(d) if j != i][:args.neighbours]
                out.append(f"| {nm} | {nmatch[i]} | {', '.join(f'{x:+.1f}' for x in V[i][:3])} | "
                           + ", ".join(f"{names[ids[j]]} ({d[j]:.1f})" for j in near) + " |")
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


def cmd_show(args) -> int:
    cfg = config_from(args)
    con, _ = open_dbs(args)
    pkeys = models_db.player_keys(con)
    ids = [p for (p,) in con.execute("SELECT player_id FROM data.player WHERE canonical_name=?", (args.name,))]
    if not ids:
        raise SystemExit(f"no player named {args.name!r}")
    as_of = args.as_of or date.today().isoformat()
    for pid in ids:
        for side in SIDES:
            sv = heavy.get_style(pkeys[pid], as_of, side, cfg=cfg, models_path=args.models,
                                 data_path=args.data)
            if sv is None:
                print(f"{pkeys[pid]} {side:6s} none"); continue
            print(f"{pkeys[pid]} {side:6s} n_matches={sv.n_matches} n_points={sv.n_points} "
                  f"fit={sv.fit_id.rsplit(':', 1)[-1]}  " + " ".join(f"{x:+.2f}" for x in sv.vector))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", type=Path, default=models_db.MODELS_DB)
    ap.add_argument("--data", type=Path, default=models_db.DATA_DB)
    ap.add_argument("--variance", type=float, default=heavy.HeavyConfig.variance)
    ap.add_argument("--max-components", type=int, default=heavy.HeavyConfig.max_components)
    ap.add_argument("--refit-months", type=int, default=heavy.HeavyConfig.refit_months)
    ap.add_argument("--min-fit-matches", type=int, default=heavy.HeavyConfig.min_fit_matches)
    ap.add_argument("--min-fit-players", type=int, default=heavy.HeavyConfig.min_fit_players)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fit")
    f.add_argument("--first", default="1990-01-01", help="earliest refit date to try")
    f.add_argument("--no-vectors", action="store_true", help="store fits only")
    r = sub.add_parser("report")
    r.add_argument("--as-of", help="default: day after the last charted edition")
    r.add_argument("--out", type=Path, default=REPORT)
    r.add_argument("--neighbours", type=int, default=5)
    r.add_argument("--min-neighbour-matches", type=int, default=20)
    s = sub.add_parser("show")
    s.add_argument("name")
    s.add_argument("--as-of")
    args = ap.parse_args(argv)
    return {"fit": cmd_fit, "report": cmd_report, "show": cmd_show}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
